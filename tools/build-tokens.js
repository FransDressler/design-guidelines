// node tools/build-tokens.js → tokens/tokens.css + tokens/fonts.js; checks WCAG contrast, exits 1 on failure
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const t = JSON.parse(fs.readFileSync(path.join(root, 'tokens/tokens.json'), 'utf8'));

const lum = h => { const c = [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16) / 255).map(x => x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
const cr = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };

let fail = 0;
const out = ['/* generated by tools/build-tokens.js from tokens.json — do not edit */'];
for (const [n, p] of Object.entries(t.palettes)) {
  for (const [a, b, min] of [['ink', 'bg', 7], ['muted', 'bg', 4.5], ['ink', 'surface', 4.5], ['accentInk', 'accent', 4.5]]) {
    const v = cr(p[a], p[b]);
    if (v < min) { fail++; console.error(`✗ ${n}: ${a}/${b} ${v.toFixed(2)} < ${min}`); }
  }
  out.push(`[data-palette="${n}"]{color-scheme:${p.scheme};--bg:${p.bg};--surface:${p.surface};--ink:${p.ink};--muted:${p.muted};--line:${p.line};--accent:${p.accent};--accent-ink:${p.accentInk};--pop:${p.pop}}`);
}
for (const [n, f] of Object.entries(t.type)) {
  const fs_ = k => Math.round(f.base * f.ratio ** k);
  out.push(`[data-type="${n}"]{--font-display:"${f.display}",serif;--font-body:"${f.body}",system-ui,sans-serif;--font-mono:"${f.mono}",ui-monospace,monospace;--display-weight:${f.displayWeight};--display-tracking:${f.tracking};--display-case:${f.uppercase ? 'uppercase' : 'none'};` +
    `--fs-micro:${Math.max(11, fs_(-2))}px;--fs-small:${Math.max(14, fs_(-1))}px;--fs-body:${f.base}px;--fs-lead:${fs_(1)}px;--fs-h3:${fs_(2)}px;--fs-h2:clamp(${fs_(2)}px,5vw,${fs_(3)}px);--fs-h1:clamp(${fs_(3)}px,8vw,${fs_(5)}px);--fs-display:clamp(${fs_(4)}px,11vw,${fs_(6)}px)}`);
}
for (const [n, r] of Object.entries(t.radius)) out.push(`[data-radius="${n}"]{--r:${r.r};--r-btn:${r.btn}}`);
for (const [n, d] of Object.entries(t.density)) out.push(`[data-density="${n}"]{--space:${d.space};--section:${d.section}}`);
fs.writeFileSync(path.join(root, 'tokens/tokens.css'), out.join('\n') + '\n');

const fam = {};
for (const [n, f] of Object.entries(t.type)) fam[n] = [f.display, f.body, f.mono].map(x => 'family=' + x.replace(/ /g, '+') + ':wght@400;500;600;700;800').join('&').replace(/(Anton|Instrument\+Serif):wght@400;500;600;700;800/g, '$1');
fs.writeFileSync(path.join(root, 'tokens/fonts.js'),
`// generated — loads the Google Fonts for <html data-type>; re-runs when data-type changes
// also: ?palette=…&type=…&radius=…&density=…&motion=…&skeleton=…&stickers=…&grain=… override the <html> data attributes (used by generator.html)
(() => {
  const q = new URLSearchParams(location.search);
  for (const k of ['palette', 'type', 'radius', 'density', 'motion', 'skeleton', 'stickers', 'grain']) if (q.get(k)) document.documentElement.dataset[k] = q.get(k);
  const F = ${JSON.stringify(fam)};
  const load = () => { const k = document.documentElement.dataset.type; if (!F[k] || document.getElementById('font-' + k)) return;
    const l = document.createElement('link'); l.id = 'font-' + k; l.rel = 'stylesheet'; l.href = 'https://fonts.googleapis.com/css2?' + F[k] + '&display=swap'; document.head.appendChild(l); };
  load(); new MutationObserver(load).observe(document.documentElement, { attributes: true, attributeFilter: ['data-type'] });
})();
`);
console.log(fail ? `${fail} Kontrastfehler` : `ok: ${Object.keys(t.palettes).length} Paletten, ${Object.keys(t.type).length} Schriftpaare, alle Kontraste ok`);
process.exit(fail ? 1 : 0);
